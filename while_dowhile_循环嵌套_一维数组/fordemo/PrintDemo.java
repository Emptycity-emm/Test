package com.atguigu.fordemo;
/*
    println("world") : 打印并换行
    print("hello") : 只打印不换行

    换行符 : "\r\n"
    System.out.println();

    \ : 转义符
    \t :  制表符 tab
 */
public class PrintDemo {
    public static void main(String[] args) {
        System.out.print("h\te\tl\tl\to");
        System.out.println();
        System.out.println("world");
    }
}
